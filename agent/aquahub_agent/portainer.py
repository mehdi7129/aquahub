"""Local first-account setup. Passwords and setup tokens never enter audit data."""
from __future__ import annotations

import json
import re
import ssl
import time
import urllib.error
import urllib.request

from .security import ApiError

URL = "https://127.0.0.1:9443"
NAME = "aqua-portainer"
_IMAGE = re.compile(r"^(?:docker\.io/)?portainer/portainer-ce(?::[A-Za-z0-9_.-]+|@sha256:[0-9a-f]{64})$")
_TOKEN = re.compile(r"\bsetup_token=[\"']?([0-9a-fA-F]{64})\b")
_ANSI = re.compile(r"\x1b\[[0-?]*[ -/]*[@-~]")
_INSPECT = ('{"id":{{json .Id}},"name":{{json .Name}},"image":{{json .Config.Image}},'
            '"running":{{json .State.Running}},"ports":{{json .NetworkSettings.Ports}}}')


class Portainer:
    def __init__(self, app):
        self.app = app

    def _resolve(self):
        ids = self.app.docker.run(["ps", "-aq", "--filter", f"name=^/{NAME}$"]).split()
        if not ids:
            raise ApiError("portainer_missing", "Le Portainer local AquaHub n’est pas installé.")
        if len(ids) != 1 or not re.fullmatch(r"[a-f0-9]{12,64}", ids[0]):
            raise ApiError("portainer_untrusted", "L’instance Portainer ne peut pas être identifiée sans ambiguïté.")
        try:
            row = json.loads(self.app.docker.run(["inspect", "--format", _INSPECT, ids[0]]))
            bindings = row.get("ports", {}).get("9443/tcp", []) or []
            if (row.get("name") != "/" + NAME or not _IMAGE.fullmatch(row.get("image", "")) or
                    not isinstance(row.get("id"), str) or not re.fullmatch(r"[a-f0-9]{64}", row["id"]) or not row["id"].startswith(ids[0]) or
                    not row.get("running") or not bindings or
                    any(binding.get("HostIp") != "127.0.0.1" or str(binding.get("HostPort")) != "9443" for binding in bindings)):
                raise ValueError("Unexpected managed instance")
            return row
        except (ValueError, TypeError, AttributeError):
            raise ApiError("portainer_untrusted", "L’instance AquaHub attendue doit être active et accessible uniquement sur 127.0.0.1:9443.") from None

    def _http(self, path, body=None, setup_token=None):
        headers = {"Content-Type": "application/json"}
        if setup_token is not None:
            headers["X-Setup-Token"] = setup_token
        request = urllib.request.Request(URL + path, data=json.dumps(body).encode() if body is not None else None, headers=headers)
        # A self-signed certificate is generated by the pinned local Portainer.
        # Disable proxies and redirects: credentials may only reach this instance.
        context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
        context.check_hostname = False
        context.verify_mode = ssl.CERT_NONE
        class NoRedirect(urllib.request.HTTPRedirectHandler):
            def redirect_request(self, req, fp, code, msg, headers, newurl):
                return None
        opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), urllib.request.HTTPSHandler(context=context), NoRedirect())
        try:
            with opener.open(request, timeout=8) as response:
                data = response.read(65537)
                if len(data) > 65536:
                    raise ApiError("portainer_response", "La réponse du Portainer local est trop volumineuse.")
                return response.status
        except urllib.error.HTTPError as error:
            try:
                if error.code == 303:
                    data = error.read(65537)
                    try:
                        expired = len(data) <= 65536 and json.loads(data).get("message") == "Administrator initialization timeout"
                    except (ValueError, AttributeError):
                        expired = False
                    if expired and path in {"/api/users/admin/check", "/api/users/admin/init"}:
                        return 303
                    raise ApiError("portainer_response", "Le Portainer local a retourné une redirection inattendue. Aucune donnée n’a été transmise à une autre adresse.")
                return error.code
            finally:
                error.close()
        except (OSError, urllib.error.URLError):
            raise ApiError("portainer_unavailable", "Le Portainer local n’est pas encore joignable. Réessayez dans quelques instants.") from None

    def _initialized(self):
        status = self._http("/api/users/admin/check")
        if status in {200, 204}:
            return True
        if status in {404, 303}:
            return False
        raise ApiError("portainer_status", "Impossible de vérifier si Portainer possède déjà son compte administrateur.")

    def status(self, params, context):
        if params:
            raise ApiError("invalid_params", "Aucun paramètre attendu.")
        try:
            self._resolve()
            initialized = self._initialized()
            return {"available": True, "managed": True, "initialized": initialized, "setup_required": not initialized, "url": URL}
        except ApiError as error:
            try:
                existing = self.app.docker.portainer()
                if existing.get("available") and existing.get("name") == "portainer":
                    return {"available": True, "managed": False, "initialized": None, "setup_required": False, "url": existing.get("url"), "reason": "Installation Portainer existante conservée."}
            except ApiError:
                pass
            return {"available": False, "managed": False, "initialized": None, "setup_required": False, "url": None, "reason": error.message, "code": error.code}

    def initialize(self, params, context):
        if set(params) != {"username", "password"}:
            raise ApiError("invalid_params", "L’identifiant et le mot de passe Portainer sont obligatoires.")
        username, password = params["username"], params["password"]
        if not isinstance(username, str) or not re.fullmatch(r"[A-Za-z0-9_.@-]{1,64}", username):
            raise ApiError("invalid_params", "L’identifiant doit contenir 1 à 64 lettres, chiffres, points, @, tirets ou caractères soulignés.")
        if not isinstance(password, str) or not 12 <= len(password) <= 72 or any(ord(c) < 32 for c in password) or len(password.encode()) > 72:
            raise ApiError("invalid_params", "Le mot de passe doit contenir au moins 12 caractères et au plus 72 octets, sans caractères de contrôle.")
        self._resolve()
        if self._initialized():
            raise ApiError("portainer_already_initialized", "Portainer possède déjà un compte administrateur. Aucun compte ni mot de passe n’a été modifié.")
        return self.app.submit_job("portainer.initialize", NAME, {"username": username}, lambda: self._initialize(username, password))

    def _setup_token(self, container_id):
        # This private unredacted buffer is never returned, logged, or persisted.
        raw = self.app.docker.run(["logs", "--tail", "200", container_id], max_bytes=262144, combine=True)
        tokens = _TOKEN.findall(_ANSI.sub("", raw))
        return tokens[-1] if tokens else None

    def _initialize(self, username, password):
        row = self._resolve()
        if self._initialized():
            raise ApiError("portainer_already_initialized", "Un administrateur existe déjà. Aucun compte n’a été modifié.")
        for attempt in range(2):
            token = self._setup_token(row["id"])
            if token:
                self._resolve()
                if self._initialized():
                    raise ApiError("portainer_already_initialized", "Un administrateur existe déjà. Aucun compte n’a été modifié.")
                code = self._http("/api/users/admin/init", {"Username": username, "Password": password}, token)
                if code in {200, 201} and self._initialized():
                    return {"initialized": True, "username": username, "url": URL}
                if code in {409} or self._initialized():
                    raise ApiError("portainer_already_initialized", "Un administrateur existe déjà. Aucun compte n’a été modifié.")
            if attempt == 0:
                # Only our verified, still-uninitialized local instance is restarted.
                latest = self._resolve()
                if latest["id"] != row["id"] or self._initialized():
                    raise ApiError("portainer_changed", "L’instance Portainer a changé. Aucun redémarrage n’a été effectué.")
                self.app.docker.run(["restart", "--time", "10", row["id"]], timeout=30)
                deadline = time.monotonic() + 20
                while time.monotonic() < deadline:
                    try:
                        self._resolve()
                        if self._initialized():
                            raise ApiError("portainer_already_initialized", "Un administrateur existe déjà. Aucun compte n’a été modifié.")
                        break
                    except ApiError as error:
                        if error.code == "portainer_already_initialized":
                            raise
                        time.sleep(.5)
        raise ApiError("portainer_setup_failed", "Le compte Portainer n’a pas pu être initialisé. Aucun compte existant n’a été remplacé ; vous pouvez réessayer.")


def register(app):
    service = Portainer(app)
    app.register_handler("portainer.status", service.status)
    app.register_handler("portainer.initialize", service.initialize, mutation=True)
    return service
